"""Spec 027: local and CI builds name the commit they were built from.

Writes include/version_commit.h with FIRMWARE_VERSION_SUFFIX ".<short commit>"
(empty on a tag build, which carries the tag instead, and when git can't say),
only when it changes, so only the files that show the version are rebuilt.
"""

import os
import subprocess
from pathlib import Path

Import("env")  # noqa: F821 - PlatformIO's SCons environment


def commit_suffix(project: Path) -> str:
    if os.environ.get("GITHUB_REF", "").startswith("refs/tags/"):
        return ""
    try:
        sha = subprocess.run(
            ["git", "rev-parse", "--short=7", "HEAD"], cwd=project, capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""
    return f".{sha}" if sha else ""


def write_header(project: Path) -> None:
    header = project / "include" / "version_commit.h"
    text = (
        "#pragma once\n"
        "// Generated by scripts/version_commit.py (spec 027); not in git.\n"
        f'#define FIRMWARE_VERSION_SUFFIX "{commit_suffix(project)}"\n'
    )
    if not header.exists() or header.read_text() != text:
        header.write_text(text)


write_header(Path(env["PROJECT_DIR"]))  # noqa: F821
